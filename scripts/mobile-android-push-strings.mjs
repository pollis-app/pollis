#!/usr/bin/env node
// Generates the Android string resources the native rich-push handler (#1599) posts with, from the
// shared `mobile.push.*` catalogue keys, so the notification copy has one source of truth with the app.
// --check exits 1 if the committed files are stale.

import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const LOCALES_DIR = join(ROOT, "frontend/src/i18n/locales");
export const RES_DIR = join(ROOT, "mobile/modules/pollis-native/android/src/main/res");
export const FILE_NAME = "pollis_push_strings.xml";
const BASE = "en";

// Catalogue key under `mobile.push` -> Android resource name.
export const KEYS = {
  channelMessages: "pollis_push_channel_messages",
  genericTitle: "pollis_push_generic_title",
  genericBody: "pollis_push_generic_body",
  you: "pollis_push_you",
  bodyAttachment: "pollis_push_body_attachment",
  bodyImage: "pollis_push_body_image",
  bodyVideo: "pollis_push_body_video",
  bodyVoice: "pollis_push_body_voice",
  bodySensitive: "pollis_push_body_sensitive",
};

/** Android string-resource escaping: XML entities plus aapt's quote/apostrophe/leading-@? rules. */
export function escapeAndroid(value) {
  let out = value
    .replace(/\\/g, "\\\\")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, '\\"')
    .replace(/'/g, "\\'")
    .replace(/\n/g, "\\n");
  if (out.startsWith("@") || out.startsWith("?")) {
    out = `\\${out}`;
  }
  return out;
}

export function valuesDir(code) {
  return code === BASE ? "values" : `values-${code}`;
}

export function render(push) {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    "<!-- GENERATED by scripts/mobile-android-push-strings.mjs from frontend/src/i18n/locales/*/mobile.json (push.*). Do not edit by hand. -->",
    "<resources>",
  ];
  for (const [key, name] of Object.entries(KEYS)) {
    const value = push?.[key];
    if (typeof value === "string" && value.length > 0) {
      lines.push(`    <string name="${name}">${escapeAndroid(value)}</string>`);
    }
  }
  lines.push("</resources>", "");
  return lines.join("\n");
}

export function expectedFiles(localesDir = LOCALES_DIR) {
  const out = {};
  for (const code of readdirSync(localesDir).sort()) {
    const file = join(localesDir, code, "mobile.json");
    if (!statSync(join(localesDir, code)).isDirectory() || !existsSync(file)) {
      continue;
    }
    const push = JSON.parse(readFileSync(file, "utf8")).push ?? {};
    out[join(valuesDir(code), FILE_NAME)] = render(push);
  }
  return out;
}

function main() {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, contents] of Object.entries(expectedFiles())) {
    const path = join(RES_DIR, rel);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === contents) {
      continue;
    }
    if (check) {
      console.error(`stale: ${rel} (run node scripts/mobile-android-push-strings.mjs)`);
      stale += 1;
      continue;
    }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
    console.log(`wrote ${rel}`);
  }
  if (stale > 0) {
    process.exit(1);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
